/**
 * mathviz — js/data/courses/integral.js
 * 课案 3：积分与黎曼和（3b1b 风格）
 *
 * 四个步骤：
 *   1. 面积的直觉        —— f(x)=x² 在 [0,2] 上，少量中点矩形引出问题
 *   2. 黎曼和的细分      —— n 滑块（核心交互），观察矩形贴合曲线
 *   3. 取样模式对比      —— left / right / mid 三种取样的精度差异
 *   4. 微积分基本定理    —— ∫₀² x² dx = x³/3 |₀² = 8/3
 *
 * 表达式幂用 ^（如 x^2）；曲线主蓝 #4f9cf9，黎曼矩形默认绿色 rgba(74,222,128,0.35)。
 *
 * 注意：course.js 的 setPath 仅按 '.' 分段，不支持 layers[0].n 这种括号写法，
 * 故 controls.bind 一律用点路径（如 "layers.0.n"）。
 */
(function () {
  'use strict';

  // 横轴 [0, 2.6] 给右侧留白，纵轴 [0, 4.5] 容纳 f(2)=4
  const AXES = { xRange: [0, 2.6], yRange: [0, 4.5] };

  const course = {
    id: 'integral',
    title: '积分与黎曼和',
    summary: '把曲线下的面积切成无数细长矩形，便是积分的全部秘密。',

    // 首页封面：一条曲线 + 几块面积条纹
    coverSVG:
      '<svg viewBox="0 0 120 80" xmlns="http://www.w3.org/2000/svg">' +
      '<rect x="0" y="0" width="120" height="80" rx="10" fill="#0f1623"/>' +
      '<g fill="rgba(74,222,128,0.30)" stroke="#4ade80" stroke-width="0.6">' +
      '<rect x="20" y="46" width="13" height="22"/>' +
      '<rect x="33" y="38" width="13" height="30"/>' +
      '<rect x="46" y="30" width="13" height="38"/>' +
      '<rect x="59" y="21" width="13" height="47"/>' +
      '<rect x="72" y="13" width="13" height="55"/>' +
      '</g>' +
      '<path d="M20 68 Q 50 52 86 8" fill="none" stroke="#4f9cf9" stroke-width="2.5"/>' +
      '<line x1="20" y1="68" x2="98" y2="68" stroke="rgba(255,255,255,0.4)" stroke-width="1"/>' +
      '<text x="60" y="76" text-anchor="middle" font-size="9" fill="rgba(255,255,255,0.55)" font-family="serif">∫₀² x²</text>' +
      '</svg>',

    steps: [
      // -----------------------------------------------------------------
      // 步骤 1：面积的直觉
      // -----------------------------------------------------------------
      {
        title: '面积的直觉',
        narrative: [
          '我们先抛一个看似简单的问题：曲线 $y=f(x)=x^2$ 从 $x=0$ 到 $x=2$ 这一段，',
          '**曲线下方的面积到底等于多少？**',
          '',
          '矩形、三角形、圆——这些规则的几何图形都有现成的面积公式。可曲线围出的形状没有公式可用，',
          '它是一块“弯曲的”区域。',
          '',
          '一个聪明的办法来自两千多年前的阿基米德：**用一堆矩形去逼近它**。把 $[0,2]$ 切成 4 份，',
          '在每段的中点处量一下函数值 $f(x)$，画出一块矩形。这 4 块绿色矩形拼起来的总面积，',
          '虽然不精确，但已经给了我们一个“差不多”的答案。',
          '',
          '问题来了：怎样才能让它从“差不多”变成“完全准确”？这，就是积分的起点。',
        ].join('\n'),

        scene: {
          axes: AXES,
          layers: [
            { type: 'riemann', fn: 'x^2', range: [0, 2], n: 4, mode: 'mid' },
            { type: 'plot', fn: 'x^2', color: '#4f9cf9', lineWidth: 2.5, range: [0, 2.4], samples: 200 },
            { type: 'point', x: 2, y: 4, radius: 4, color: '#ff8c42', label: '(2, 4)' },
          ],
        },
        controls: [],
      },

      // -----------------------------------------------------------------
      // 步骤 2：黎曼和的细分（核心交互）
      // -----------------------------------------------------------------
      {
        title: '黎曼和的细分',
        narrative: [
          '现在把权利交给你的手指——拖动下面的 **矩形数 n** 滑块。',
          '',
          '把区间 $[0,2]$ 切成 $n$ 等份，每份宽 $\\Delta x = \\dfrac{2-0}{n} = \\dfrac{2}{n}$。在每一小段的中点取样，',
          '得到函数值 $f(x_i^*)$，于是这 $n$ 块矩形面积之和为：',
          '',
          '$$R_n \\;=\\; \\sum_{i=1}^{n} f(x_i^{*})\\,\\Delta x$$',
          '',
          '这就是**黎曼和**。注意看：当 $n$ 很小，矩形参差不齐，与蓝色曲线之间留着明显的缝隙；',
          '但当 $n$ 越来越大，缝隙越来越小，矩形的顶端几乎“贴着”曲线走。',
          '',
          '于是那个让所有数学家激动的瞬间出现了：',
          '$$\\int_0^2 x^2\\,dx \\;=\\; \\lim_{n \\to \\infty} R_n$$',
          '',
          '积分，本质就是黎曼和在分割无限细化时的**极限**。',
        ].join('\n'),

        scene: {
          axes: AXES,
          layers: [
            { type: 'riemann', fn: 'x^2', range: [0, 2], n: 8, mode: 'mid' },
            { type: 'plot', fn: 'x^2', color: '#4f9cf9', lineWidth: 2.5, range: [0, 2.4], samples: 200 },
          ],
        },
        controls: [
          {
            name: 'n',
            label: '矩形数 n',
            type: 'slider',
            min: 1,
            max: 200,
            step: 1,
            value: 8,
            bind: 'layers.0.n',
          },
        ],
      },

      // -----------------------------------------------------------------
      // 步骤 3：取样模式对比
      // -----------------------------------------------------------------
      {
        title: '取样模式对比',
        narrative: [
          '刚才我们在**每段的中点**取样。其实取样点选在哪儿都可以，常见的有三种：',
          '',
          '- **左端点**（left）：取 $x_i^* = x_{i-1}$，矩形顶端从曲线**下方**贴上去，整体**偏小**；',
          '- **右端点**（right）：取 $x_i^* = x_i$，矩形顶端从曲线**上方**压下来，整体**偏大**；',
          '- **中点**（mid）：取 $x_i^* = \\tfrac{x_{i-1}+x_i}{2}$，矩形不偏不倚，最贴近真值。',
          '',
          '对于 $f(x)=x^2$ 这种递增函数，**左点法总是低估、右点法总是高估**，真实的面积被夹在两者之间。',
          '而中点法同样取 $n$ 块矩形，误差却小得多——它把每段内的“偏差”相互抵消了大部分。',
          '',
          '拖动滑块在三种模式间切换，对比一下矩形的“贴合程度”。三种方式取极限都会收敛到同一个积分值，',
          '区别只在于“走得多快”到达答案——这就是数值积分里中点法精度更高的根源。',
        ].join('\n'),

        scene: {
          axes: AXES,
          layers: [
            { type: 'riemann', fn: 'x^2', range: [0, 2], n: 8, mode: 'mid' },
            { type: 'plot', fn: 'x^2', color: '#4f9cf9', lineWidth: 2.5, range: [0, 2.4], samples: 200 },
          ],
        },
        controls: [
          {
            name: 'mode',
            label: '取样模式（0=左 / 1=右 / 2=中）',
            type: 'slider',
            min: 0,
            max: 2,
            step: 1,
            value: 2,
          },
          {
            name: 'n',
            label: '矩形数 n',
            type: 'slider',
            min: 1,
            max: 200,
            step: 1,
            value: 8,
            bind: 'layers.0.n',
          },
        ],

        // mode 滑块输出整数 0/1/2，这里映射为引擎所需的字符串
        onControl: function (name, value, scene) {
          if (name !== 'mode') return;
          var modes = ['left', 'right', 'mid'];
          if (scene.layers && scene.layers[0]) {
            scene.layers[0].mode = modes[Math.round(value)] || 'mid';
          }
        },
      },

      // -----------------------------------------------------------------
      // 步骤 4：微积分基本定理
      // -----------------------------------------------------------------
      {
        title: '微积分基本定理',
        narrative: [
          '把矩形数推到 $n=200$，绿色区域已经填得满满当当——它和真正的曲线下面积，肉眼几乎无法分辨。',
          '那么这块面积到底是多少？',
          '',
          '牛顿和莱布尼茨各自独立给出了同一个惊人的结论：**只要能找到一个原函数 $F(x)$，使得 $F\'(x)=f(x)$，',
          '那么定积分就是原函数在两端点处的差**：',
          '',
          '$$\\boxed{\\,\\int_a^{b} f(x)\\,dx \\;=\\; F(b) - F(a)\\,}$$',
          '',
          '对 $f(x)=x^2$，原函数是 $F(x)=\\dfrac{x^3}{3}$（因为 $\\left(\\tfrac{x^3}{3}\\right)\' = x^2$）。代入：',
          '',
          '$$\\int_0^{2} x^2\\,dx \\;=\\; \\left.\\frac{x^3}{3}\\right|_{0}^{2} \\;=\\; \\frac{2^3}{3} - \\frac{0^3}{3} \\;=\\; \\boxed{\\frac{8}{3} \\approx 2.667}$$',
          '',
          '注意这奇妙的一刻：黎曼和的极限让我们从**局部小块**逼近面积，而基本定理让我们**一口气算出**这块面积。',
          '微分（求导）与积分（求和）这对看似相反的操作，通过原函数联系在了一起——这就是微积分的灵魂。',
        ].join('\n'),

        scene: {
          axes: AXES,
          layers: [
            // 用极大 n 的矩形群模拟“连续填充”的面积
            { type: 'riemann', fn: 'x^2', range: [0, 2], n: 200, mode: 'mid' },
            { type: 'plot', fn: 'x^2', color: '#4f9cf9', lineWidth: 2.5, range: [0, 2.4], samples: 200 },
            // 面积值标注
            {
              type: 'text',
              x: 1.0,
              y: 3.4,
              text: '面积 = 8/3 ≈ 2.667',
              color: '#4ade80',
              fontSize: 14,
            },
            // 积分符号标注
            {
              type: 'text',
              x: 1.0,
              y: 3.85,
              text: '∫₀² x² dx',
              color: '#9aa7b4',
              fontSize: 12,
            },
          ],
        },
        controls: [],
      },
    ],
  };

  window.COURSES.register(course);
})();
